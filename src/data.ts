// HELPER FOR ZERO-DEPENDENCY LIVE DATABASE PROXYING
const STORAGE_KEY = 'archive_protocol_master_db';

function getLiveDb() {
  if (typeof window === 'undefined') {
    return {
      watches: STATIC_WATCH_DATA,
      config_options: STATIC_CONFIG_OPTIONS,
    };
  }
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (!stored) {
    return {
      watches: STATIC_WATCH_DATA,
      config_options: STATIC_CONFIG_OPTIONS,
    };
  }
  try {
    const parsed = JSON.parse(stored);
    const watches = parsed.watches || STATIC_WATCH_DATA;

    // Dynamically append any missing default watches that weren't stored in localStorage yet
    const existingIds = new Set(watches.map((w: any) => w.id));
    const missingWatches = STATIC_WATCH_DATA.filter(
      (dw) => !existingIds.has(dw.id),
    );

    const mergedWatches = [
      ...watches.map((w: any) => {
        const defaultWatch = STATIC_WATCH_DATA.find((dw) => dw.id === w.id);
        if (defaultWatch) {
          const merged = {
            ...defaultWatch,
            ...w,
            specs: { ...defaultWatch.specs, ...w.specs },
          };
          if (
            merged.id === 'primal-mama' &&
            merged.name.includes('Alligator')
          ) {
            merged.name = defaultWatch.name;
          }
          return merged;
        }
        return w;
      }),
      ...missingWatches,
    ];

    const cardOrder =
      Array.isArray(parsed.card_order) && parsed.card_order.length > 0
        ? parsed.card_order
        : [
            'primal-mama',
            'toot-and-scute-unusual-simulation-service',
            'perfect-beeing',
            'blessed-and-the-bounded',
            'mythrokahn',
          ];

    if (Array.isArray(cardOrder) && cardOrder.length > 0) {
      const orderMap = new Map(
        cardOrder.map((id: string, index: number) => [id, index]),
      );
      mergedWatches.sort((a: any, b: any) => {
        const idxA = orderMap.has(a.id) ? orderMap.get(a.id)! : 999;
        const idxB = orderMap.has(b.id) ? orderMap.get(b.id)! : 999;
        return idxA - idxB;
      });
    }

    return {
      watches: mergedWatches,
      config_options: parsed.config_options || STATIC_CONFIG_OPTIONS,
    };
  } catch (e) {
    return {
      watches: STATIC_WATCH_DATA,
      config_options: STATIC_CONFIG_OPTIONS,
    };
  }
}

// Transparent dynamic Proxy for WATCH_DATA array
export const WATCH_DATA: Watch[] = new Proxy([] as Watch[], {
  get(target, prop, receiver) {
    const liveWatches = getLiveDb().watches;
    const value = Reflect.get(liveWatches, prop, liveWatches);
    if (typeof value === 'function') {
      return value.bind(liveWatches);
    }
    return value;
  },
  getOwnPropertyDescriptor(target, prop) {
    const liveWatches = getLiveDb().watches;
    return Reflect.getOwnPropertyDescriptor(liveWatches, prop);
  },
  ownKeys(target) {
    const liveWatches = getLiveDb().watches;
    return Reflect.ownKeys(liveWatches);
  },
});

// Transparent dynamic Proxy for CONFIG_OPTIONS object
export const CONFIG_OPTIONS = new Proxy({} as typeof STATIC_CONFIG_OPTIONS, {
  get(target, prop, receiver) {
    const liveConfig = getLiveDb().config_options;
    return Reflect.get(liveConfig, prop, liveConfig);
  },
  getOwnPropertyDescriptor(target, prop) {
    const liveConfig = getLiveDb().config_options;
    return Reflect.getOwnPropertyDescriptor(liveConfig, prop);
  },
  ownKeys(target) {
    const liveConfig = getLiveDb().config_options;
    return Reflect.ownKeys(liveConfig);
  },
});
